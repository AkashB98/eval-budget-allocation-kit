"""CLI: demo / report / check.

SYNTHETIC DATA ONLY -- every score is generated by a seeded scripted
agent; no LLM, no network, no real eval data.

Exit codes:
  check : 0 = recommended allocation beats every naive baseline on
            held-out simulation, 1 = it does not, 2 = bad input
  others: 0 = success, 2 = usage / IO error
"""
from __future__ import annotations

import argparse
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from allocator import DEFAULT_BUDGET  # noqa: E402
from generator import REGIMES  # noqa: E402
from report import build_report  # noqa: E402

EXIT_OK, EXIT_FAIL, EXIT_ERROR = 0, 1, 2


def _dump(obj):
    print(json.dumps(obj, indent=2, sort_keys=True))


def _validate(args):
    if args.budget < 1000:
        raise ValueError("budget must be >= 1000 (one rollout)")
    if args.budget > 10_000_000:
        raise ValueError("budget unreasonably large")


def cmd_report(args):
    _validate(args)
    _dump(build_report(budget=args.budget, regime=args.regime))
    return EXIT_OK


def cmd_check(args):
    if getattr(args, "input", None) and not os.path.exists(args.input):
        print(f"error: input not found: {args.input}", file=sys.stderr)
        return EXIT_ERROR
    _validate(args)
    report = build_report(budget=args.budget, regime=args.regime)
    rec = report["recommended"]
    print(f"recommended Q={rec['n_questions']} T={rec['n_traj']} "
          f"R={rec['n_repeats']} empirical_se={rec['empirical_se']}")
    ok = True
    for name, base in sorted(report["baselines"].items()):
        beats = rec["empirical_se"] < base["empirical_se"]
        ok = ok and beats
        print(f"baseline {name}: Q={base['n_questions']} T={base['n_traj']} "
              f"R={base['n_repeats']} empirical_se={base['empirical_se']} "
              f"beats={beats}")
    if ok:
        print("check PASS: recommended allocation beats all naive baselines "
              "on held-out simulation")
        return EXIT_OK
    print("check FAIL: recommended allocation does not beat all baselines")
    return EXIT_FAIL


def cmd_demo(args):
    import demo as demo_mod
    try:
        return demo_mod.run()
    except AssertionError as exc:
        print(f"demo FAILED: {exc}", file=sys.stderr)
        return EXIT_FAIL


def build_parser():
    p = argparse.ArgumentParser(
        prog="cli.py",
        description="Eval budget allocation kit (synthetic data only).")
    sub = p.add_subparsers(dest="cmd", required=True)
    for name, fn, helptext in (
            ("report", cmd_report, "pilot -> allocation -> held-out report"),
            ("check", cmd_check, "CI gate: 0 beats baselines / 1 does not / 2 error")):
        sp = sub.add_parser(name, help=helptext)
        sp.add_argument("--budget", type=int, default=DEFAULT_BUDGET)
        sp.add_argument("--regime", choices=sorted(REGIMES), default="standard")
        sp.add_argument("--input", default=None)
        sp.set_defaults(func=fn)
    sub.add_parser("demo", help="run the end-to-end demo").set_defaults(func=cmd_demo)
    return p


def main(argv=None):
    args = build_parser().parse_args(argv)
    try:
        return args.func(args)
    except (OSError, ValueError, KeyError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return EXIT_ERROR


if __name__ == "__main__":
    sys.exit(main())
